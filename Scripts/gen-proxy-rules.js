#!/usr/bin/env node
// Generate Tinycast/Features/Proxy/Model/ProxyRuleNames.generated.swift.
//
// Usage: node Scripts/gen-proxy-rules.js
// Reads the MetaCubeX/meta-rules-dat `meta` branch through the GitHub API and lists every geosite and
// geoip rule set it ships as .mrs, the format the proxy's routes download. Run occasionally, commit
// the output. The list only powers search and an offline existence check: a name added upstream
// after the last run is still accepted once the catalog answers for it.
"use strict";

const fs = require("fs");
const path = require("path");

const REPO = "MetaCubeX/meta-rules-dat";
const BRANCH = "meta";
const OUT = path.join(__dirname, "..", "Tinycast/Features/Proxy/Model/ProxyRuleNames.generated.swift");
// meta-rules-dat held 1923 geosite and 260 geoip sets in October 2026; far fewer is a bad response.
const MIN_GEOSITE = 1500;
const MIN_GEOIP = 200;

async function api(pathname) {
  const response = await fetch(`https://api.github.com/repos/${REPO}/${pathname}`, {
    headers: { Accept: "application/vnd.github+json", "User-Agent": "tinycast-gen-proxy-rules" },
  });
  if (!response.ok) throw new Error(`${pathname} -> HTTP ${response.status}`);
  return response.json();
}

async function subtree(tree, name) {
  const entry = tree.tree.find((e) => e.type === "tree" && e.path === name);
  if (!entry) throw new Error(`no ${name} directory`);
  return api(`git/trees/${entry.sha}`);
}

function names(tree) {
  if (tree.truncated) throw new Error("the GitHub API truncated a directory listing");
  return tree.tree
    .filter((e) => e.type === "blob" && e.path.endsWith(".mrs"))
    .map((e) => e.path.slice(0, -".mrs".length))
    .sort();
}

function literal(list) {
  for (const name of list) {
    if (!/^[A-Za-z0-9@!._-]+$/.test(name)) throw new Error(`unexpected rule set name: ${name}`);
  }
  return list.map((name) => `        ${name}`).join("\n");
}

async function main() {
  const branch = await api(`branches/${BRANCH}`);
  const revision = branch.commit.sha;
  const root = await api(`git/trees/${revision}`);
  const geo = await subtree(root, "geo");
  const geosite = names(await subtree(geo, "geosite"));
  const geoip = names(await subtree(geo, "geoip"));
  if (geosite.length < MIN_GEOSITE || geoip.length < MIN_GEOIP) {
    throw new Error(`only ${geosite.length} geosite and ${geoip.length} geoip sets`);
  }
  const swift = `// Generated by Scripts/gen-proxy-rules.js from ${REPO}@${revision.slice(0, 12)}. Do not edit.

/// The geosite and geoip rule sets the catalog shipped as .mrs when this was generated.
enum ProxyRuleNames {
    static let geosite = """
${literal(geosite)}
        """

    static let geoip = """
${literal(geoip)}
        """
}
`;
  fs.writeFileSync(OUT, swift);
  console.log(`${geosite.length} geosite and ${geoip.length} geoip sets from ${revision.slice(0, 12)}`);
}

main().catch((error) => {
  console.error(`gen-proxy-rules: ${error.message}`);
  process.exit(1);
});
