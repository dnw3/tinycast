import AppKit
import ImageIO
import UniformTypeIdentifiers

@MainActor
@Observable
final class ClipboardManager {
    /// Marker we attach to the pasteboard when *we* write to it, so polling ignores our own pastes.
    static let internalType = NSPasteboard.PasteboardType("com.tinycast.internal")

    /// Longest text captured in characters; bigger copies are skipped, truncation losing the tail.
    nonisolated static let maxTextLength = 1_000_000

    /// Markers put on secret copies by password managers, browsers and the OS.
    static let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("com.apple.is-sensitive"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.agilebits.onepassword"),
        .init("com.typeit4me.clipping"),
        .init("net.antelle.keeweb"),
        .init("Pasteboard generator type")
    ]

    /// Every bitmap flavour is stored as PNG, so the history keeps one image format.
    nonisolated static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, .tiff, .init(UTType.jpeg.identifier), .init(UTType.heic.identifier)
    ]

    /// The reader's own pause, for this session only: a relaunch always records again.
    private(set) var isRecordingPaused = false

    @ObservationIgnored private let store: ClipboardStore
    @ObservationIgnored private let settings: AppSettings
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var sessionTokens: [NotificationToken] = []
    @ObservationIgnored private var lastChangeCount = 0
    @ObservationIgnored private var isCapturing = false
    @ObservationIgnored private var isCapturePaused = false

    init(store: ClipboardStore, settings: AppSettings) {
        self.store = store
        self.settings = settings
    }

    // Isolated so teardown can touch the main-actor timer; the poll block is already weak.
    isolated deinit {
        timer?.invalidate()
    }

    func start() {
        guard !isCapturing else { return }
        isCapturing = true
        installSessionObservers()
        startPolling()
    }

    func stop() {
        isCapturing = false
        sessionTokens = []
        stopPolling()
    }

    // Fast user switching: another session's clipboard isn't ours, so stop waking up for it.
    private func installSessionObservers() {
        guard sessionTokens.isEmpty else { return }
        let center = NSWorkspace.shared.notificationCenter
        sessionTokens = [
            NotificationToken(
                center.addObserver(
                    forName: NSWorkspace.sessionDidResignActiveNotification, object: nil,
                    queue: .main
                ) { [weak self] _ in
                    MainActor.assumeIsolated { self?.stopPolling() }
                }, center: center),
            NotificationToken(
                center.addObserver(
                    forName: NSWorkspace.sessionDidBecomeActiveNotification, object: nil,
                    queue: .main
                ) { [weak self] _ in
                    MainActor.assumeIsolated { self?.startPolling() }
                }, center: center)
        ]
    }

    // Re-baselining first is what stops a clip made in another session reading as new on resume.
    private func startPolling() {
        guard isCapturing, timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stopPolling() {
        timer?.invalidate()
        timer = nil
    }

    // Drain first: the real copy must reach history before we overwrite the pasteboard.
    func prepareForTinycastPasteboardMutation() {
        guard isCapturing else { return }
        poll()
    }

    /// For a ⌘C Tinycast sends itself, whose copy is read and restored but never recorded.
    func pauseCapture() {
        prepareForTinycastPasteboardMutation()
        isCapturePaused = true
    }

    func resumeCapture() {
        isCapturePaused = false
    }

    func setRecordingPaused(_ paused: Bool) {
        // Drained first, so a copy made just before pausing is still recorded.
        if paused { prepareForTinycastPasteboardMutation() }
        isRecordingPaused = paused
    }

    // Load-bearing: a mismatched count means a foreign write the next poll must still see.
    func synchronizeAfterTinycastPasteboardMutation(changeCount: Int) {
        guard NSPasteboard.general.changeCount == changeCount else { return }
        lastChangeCount = changeCount
    }

    /// A Finder select-all must not insert ten thousand rows on one poll tick.
    nonisolated static let maxCapturedFiles = 32

    /// Reclaimable roots, without the `/private` that `resolvingSymlinksInPath` strips.
    nonisolated static let volatileRoots = [
        "/tmp/", "/var/tmp/", "/var/folders/", NSHomeDirectory() + "/Library/Caches/"
    ]

    /// Both parameters are injected environment facts, so a harness can drive its own scratch.
    nonisolated static func fileURLs(
        on pasteboard: NSPasteboard, volatileRoots roots: [String] = volatileRoots
    ) -> [String]? {
        let durable = PasteboardFiles.urls(on: pasteboard, limit: maxCapturedFiles) {
            isDurable($0, roots: roots)
        }
        // Nil rather than empty, so a copied `http` URL falls through and stays a link.
        guard !durable.isEmpty else { return nil }
        // Reversed on insert, so the first file copied ends up leading the history.
        return durable.map(\.standardizedFileURL.path).reversed()
    }

    /// An app that stages a temp file beside better inline content must keep the inline content.
    nonisolated private static func isDurable(_ url: URL, roots: [String]) -> Bool {
        guard FileManager.default.fileExists(atPath: url.path) else { return false }
        var path = url.resolvingSymlinksInPath().path
        if path.hasPrefix("/private/") { path.removeFirst("/private".count) }
        return !roots.contains { path.hasPrefix($0) }
    }

    func recordCapture(_ png: Data, sourceBundleID: String?) {
        guard isCapturing, accepts(sourceBundleID) else { return }
        store.addImage(png, sourceBundleID: sourceBundleID) { [weak self] in
            self?.accepts(sourceBundleID) == true
        }
    }

    /// Asked again after an image's off-main work, since the reader can pause or exclude meanwhile.
    private func accepts(_ sourceBundleID: String?) -> Bool {
        guard !isRecordingPaused, settings.clipboardEnabled else { return false }
        return sourceBundleID.map { !settings.clipboardDisabledApps.contains($0) } ?? true
    }

    /// ImageIO decodes TIFF, JPEG and HEIC alike; nil when the bytes are not an image.
    nonisolated static func pngData(from data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
            CGImageSourceGetCount(source) > 0
        else { return nil }
        let png = NSMutableData()
        guard
            let destination = CGImageDestinationCreateWithData(
                png, UTType.png.identifier as CFString, 1, nil)
        else { return nil }
        CGImageDestinationAddImageFromSource(destination, source, 0, nil)
        return CGImageDestinationFinalize(destination) ? png as Data : nil
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard !isCapturePaused, pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        // The count still advances while paused, so resuming never records a paused copy.
        if isRecordingPaused || pb.types?.contains(Self.internalType) == true { return }

        // Never record secrets: skip copies tagged sensitive by any of the marker owners.
        if let types = pb.types, !Set(types).isDisjoint(with: Self.sensitiveTypes) { return }

        // The pasteboard carries no source, so attribute it to the frontmost app.
        let sourceBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let sourceBundleID, settings.clipboardDisabledApps.contains(sourceBundleID) { return }

        // Ahead of the text branch: Finder puts the file's *name* on `.string` beside its URL.
        if let paths = Self.fileURLs(on: pb) {
            store.addFiles(paths, sourceBundleID: sourceBundleID)
            return
        }

        if let text = pb.string(forType: .string),
            !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        {
            guard Self.fitsTextLimit(text) else { return }
            store.addText(
                text, richText: Self.richText(on: pb), sourceBundleID: sourceBundleID
            ) { [weak self] in
                self?.accepts(sourceBundleID) == true
            }
            return
        }

        if let type = pb.availableType(from: Self.imageTypes), let data = pb.data(forType: type) {
            let isPNG = type == .png
            // A big re-encode can take 100ms+, so keep the poll off that path.
            Task.detached(priority: .utility) { [weak self] in
                guard let png = isPNG ? data : Self.pngData(from: data) else { return }
                await self?.recordCapture(png, sourceBundleID: sourceBundleID)
            }
        }
    }

    /// RTF only: HTML can pull remote resources, and RTFD or web archives carry whole attachments.
    nonisolated static func richText(on pasteboard: NSPasteboard) -> Data? {
        guard pasteboard.types?.contains(.rtf) == true,
            let data = pasteboard.data(forType: .rtf), !data.isEmpty,
            data.count <= ClipboardStore.maxRichTextBytes
        else { return nil }
        return data
    }

    /// `utf8.count` is O(1), so a giant copy is refused before any character walk begins.
    nonisolated static func fitsTextLimit(_ text: String) -> Bool {
        text.utf8.count <= maxTextLength || (text.utf8.count <= 4 * maxTextLength
            && text.count <= maxTextLength)
    }
}
